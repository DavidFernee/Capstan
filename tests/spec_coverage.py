#!/usr/bin/env python3
"""Conformance coverage: every area in docs/SPEC.md's "Conformance areas" table
must be declared by at least one test (`// spec: area ...`). Also rejects tests
that name an area the spec does not define. Writes docs/CONFORMANCE.md."""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = open(os.path.join(ROOT, "docs/SPEC.md")).read()
table = spec.split("## Conformance areas", 1)[1]
areas = {m.group(1): m.group(2).strip() for m in re.finditer(r"^\| `([a-z.]+)` \| (.+?) \|$", table, re.M)}
tests = {}
for p in sorted(glob.glob(os.path.join(ROOT, "tests/*/*.cap"))):
    m = re.search(r"^// spec: (.+)$", open(p, encoding="latin-1").read(), re.M)
    if m:
        tests[os.path.relpath(p, os.path.join(ROOT, "tests"))] = m.group(1).split()
unknown = sorted({(t, a) for t, ids in tests.items() for a in ids if a not in areas})
by_area = {a: [t for t, ids in tests.items() if a in ids] for a in areas}
uncovered = [a for a, ts in by_area.items() if not ts]
lines = ["# Conformance matrix", "", "Generated by `tests/spec_coverage.py` from the `// spec:` lines in the tests.", "",
         f"**{len(areas)} areas, {len(tests)} tagged tests, {len(areas) - len(uncovered)} areas covered.**", "",
         "| Area | Covers | Tests |", "|---|---|---|"]
for a, desc in areas.items():
    ts = by_area[a]
    lines.append(f"| `{a}` | {desc} | {len(ts)}: " + ", ".join(f"`{t}`" for t in ts[:6]) + (" ..." if len(ts) > 6 else "") + " |")
open(os.path.join(ROOT, "docs/CONFORMANCE.md"), "w").write("\n".join(lines) + "\n")
for t, a in unknown:
    print(f"  {t}: unknown spec area '{a}'")
for a in uncovered:
    print(f"  spec area '{a}' has no tests")
print(f"spec coverage: {len(areas) - len(uncovered)}/{len(areas)} areas covered by {len(tests)} tagged tests")
sys.exit(1 if uncovered or unknown else 0)
